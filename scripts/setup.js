#!/usr/bin/env node
// One-command setup: log in to Cloudflare, deploy the Worker, set TUNNEL_TOKEN and
// write the Worker URL + token into data/config.json for the local client.
//
//   npm run setup                 deploy (reuses the saved token if there is one)
//   npm run setup -- --new-token  deploy and rotate the token

import { spawn } from "node:child_process";
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import readline from "node:readline/promises";
import { ConfigStore, ROOT_DIR, isValidRelayUrl, normalizeRelayUrl } from "../client/src/config.js";
import { checkRelay } from "../client/src/connection.js";

const WORKER_DIR = path.join(ROOT_DIR, "worker");
// Always name the config explicitly: wrangler otherwise prefers any wrangler.json(c)
// it finds in a parent folder (e.g. one auto-generated by `wrangler deploy` run at the repo root).
const CONFIG = ["--config", "wrangler.toml"];
const rotateToken = process.argv.includes("--new-token");
const isWindows = process.platform === "win32";

const bold = (s) => (process.stdout.isTTY ? `\x1b[1m${s}\x1b[0m` : s);
const green = (s) => (process.stdout.isTTY ? `\x1b[32m${s}\x1b[0m` : s);
const red = (s) => (process.stdout.isTTY ? `\x1b[31m${s}\x1b[0m` : s);

function step(n, title) {
  console.log(`\n${bold(`[${n}/5] ${title}`)}`);
}

// Runs a command in worker/. `capture` tees stdout so we can parse it; `input` is piped to stdin.
function run(cmd, args, { capture = false, input } = {}) {
  return new Promise((resolve, reject) => {
    const child = spawn(cmd, args, {
      cwd: WORKER_DIR,
      shell: isWindows, // npm/npx are .cmd files on Windows
      stdio: [input === undefined ? "inherit" : "pipe", capture ? "pipe" : "inherit", "inherit"],
    });
    let out = "";
    if (capture) {
      child.stdout.on("data", (d) => {
        out += d;
        process.stdout.write(d);
      });
    }
    if (input !== undefined) child.stdin.end(input);
    child.on("error", reject);
    child.on("close", (code) => (code === 0 ? resolve(out) : reject(new Error(`"${cmd} ${args.join(" ")}" thất bại (mã ${code})`))));
  });
}

async function ask(question) {
  const rl = readline.createInterface({ input: process.stdin, output: process.stdout });
  try {
    return (await rl.question(question)).trim();
  } finally {
    rl.close();
  }
}

async function main() {
  if (typeof WebSocket === "undefined") throw new Error(`Cần Node.js 22 trở lên (đang dùng ${process.version}).`);
  console.log(bold("Mini Tunnel — cài đặt Cloudflare Worker"));

  step(1, "Chuẩn bị wrangler (Cloudflare CLI)");
  if (!fs.existsSync(path.join(WORKER_DIR, "node_modules", "wrangler"))) {
    await run("npm", ["install", "--no-fund", "--no-audit"]);
  } else {
    console.log("Đã có wrangler.");
  }

  step(2, "Đăng nhập Cloudflare");
  const who = await run("npx", ["wrangler", "whoami"], { capture: true });
  if (/not authenticated/i.test(who)) {
    console.log("Trình duyệt sẽ mở để bạn đăng nhập và cấp quyền cho wrangler…");
    await run("npx", ["wrangler", "login"]);
  }

  step(3, "Deploy Worker");
  let deployOut;
  try {
    deployOut = await run("npx", ["wrangler", "deploy", ...CONFIG], { capture: true });
  } catch (err) {
    console.log(red("\nDeploy thất bại."));
    console.log(
      "Nếu lỗi nhắc tới workers.dev subdomain: mở https://dash.cloudflare.com → Workers & Pages,\n" +
        "tạo subdomain workers.dev (miễn phí) rồi chạy lại: npm run setup",
    );
    throw err;
  }
  let relayUrl = deployOut.match(/https:\/\/[a-z0-9.-]+\.workers\.dev/i)?.[0];
  if (!relayUrl) {
    relayUrl = await ask("\nKhông đọc được URL từ output. Dán Worker URL (https://….workers.dev): ");
  }
  relayUrl = normalizeRelayUrl(relayUrl);
  if (!isValidRelayUrl(relayUrl)) throw new Error(`Worker URL không hợp lệ: ${relayUrl}`);
  console.log(`Worker URL: ${green(relayUrl)}`);

  step(4, "Tạo token và lưu vào Worker (secret TUNNEL_TOKEN)");
  const existing = new ConfigStore().data.token;
  const token = !rotateToken && existing ? existing : crypto.randomBytes(32).toString("base64url");
  console.log(token === existing ? "Dùng lại token đã lưu trong data/config.json." : "Đã tạo token ngẫu nhiên mới.");
  await run("npx", ["wrangler", "secret", "put", "TUNNEL_TOKEN", ...CONFIG], { input: `${token}\n` });

  step(5, "Lưu cấu hình client và kiểm tra kết nối");
  // Re-read right before writing so tunnels edited in the dashboard meanwhile are kept.
  const store = new ConfigStore();
  store.setConnection({ relayUrl, token });
  console.log(`Đã ghi ${store.file}`);

  // A first deploy can take a minute or two to reach every Cloudflare edge (404 meanwhile),
  // and the secret a few more seconds.
  let check = await checkRelay(relayUrl, token);
  if (!check.ok) process.stdout.write("Đang chờ Cloudflare kích hoạt Worker (lần deploy đầu có thể mất 1–2 phút)");
  for (let i = 0; i < 30 && !check.ok; i++) {
    await new Promise((r) => setTimeout(r, 4000));
    process.stdout.write(".");
    check = await checkRelay(relayUrl, token);
  }
  if (!check.ok) {
    console.log(red(`\nChưa kết nối được: ${check.message}`));
    console.log("Worker có thể vẫn đang được kích hoạt. Cứ chạy npm start — client sẽ tự thử kết nối lại.");
  } else {
    console.log(green("\nWorker hoạt động và token hợp lệ."));
  }

  console.log(`\n${bold("Xong!")} Tiếp theo:`);
  console.log(`  1. Chạy client:   ${bold("npm start")}   (hoặc nhấp đúp start.cmd trên Windows)`);
  console.log(`  2. Mở dashboard:  ${bold("http://127.0.0.1:8787")}  → Thêm tunnel`);
  console.log("  Nếu client đang chạy sẵn, nó sẽ tự nhận cấu hình mới.\n");
}

main().catch((err) => {
  console.error(red(`\nLỗi: ${err.message}`));
  process.exit(1);
});
